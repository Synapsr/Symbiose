// Writes src/db/migrations.ts: the SQL migrations of drizzle/ as strings, for
// hosts that can't read them from a folder at run time (the app). The server
// still reads drizzle/ itself. `--check` fails when the file is out of date
// (CI), so a new migration can't reach the server without reaching the app.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const journal = JSON.parse(readFileSync(join(root, 'drizzle/meta/_journal.json'), 'utf8'));
const target = join(root, 'src/db/migrations.ts');

const entries = journal.entries.map((entry) => ({
  idx: entry.idx,
  when: entry.when,
  tag: entry.tag,
  breakpoints: entry.breakpoints,
  sql: readFileSync(join(root, 'drizzle', `${entry.tag}.sql`), 'utf8'),
}));

const output = `// Generated by scripts/bundle-migrations.mjs from drizzle/: do not edit.
// pnpm --filter @symbiose/core db:generate writes a migration and this file.

export interface BundledMigration {
  idx: number;
  /** drizzle-kit's timestamp: what decides whether a migration was applied. */
  when: number;
  tag: string;
  breakpoints: boolean;
  sql: string;
}

export const MIGRATIONS: BundledMigration[] = ${JSON.stringify(entries, null, 2)};
`;

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(target, 'utf8');
  } catch {}
  if (current !== output) {
    console.error('packages/core/src/db/migrations.ts is out of date: run pnpm --filter @symbiose/core db:generate (or node scripts/bundle-migrations.mjs).');
    process.exit(1);
  }
  console.log('Bundled migrations are up to date.');
} else {
  writeFileSync(target, output);
  console.log(`Wrote ${entries.length} migrations to src/db/migrations.ts`);
}
